# Steps that do not count under Tier 1 (distinct languages), and why.
# Every other step counts once under both tiers. See ../RECORDS.md for the rules.
MERGED = {
  "Ook!" => "same language as Brainfuck with the words swapped",
  "JSFuck" => "a subset of JavaScript, run by node",
  "WebAssembly (Binary format)" => "same language as WebAssembly (Text format), another format",
  "FORTRAN77" => "an older version of Fortran (Fortran90 counts)",
  "Gzip" => "a file format, not a programming language",
  "yash" => "another POSIX sh implementation (dash counts)",
  "mksh" => "another ksh implementation (ksh counts)",
  "Yabasic" => "another BASIC dialect (BASIC (bwBASIC) counts)",
}
NOTES = {
  "Perl 6" => "renamed Raku in 2019; its own language, separate from Perl 5",
}
NEW = RunSteps[1, 23].map {|s| s.name }

raise "unknown name in MERGED" unless (MERGED.keys - RunSteps.map {|s| s.name }).empty?

t1 = RunSteps.size - MERGED.size
rows = RunSteps.map.with_index do |s, i|
  tier = MERGED[s.name] ? "T2 only" : "T1"
  note = MERGED[s.name] || NOTES[s.name] || ""
  "| #{ i + 1 } | #{ s.name } | #{ tier } | #{ NEW.include?(s.name) ? "this fork" : "mame" } | #{ note } |"
end

File.write("../LANGUAGES.md", <<END)
# Languages

Every step of the relay, in run order, with its record status. [RECORDS.md](RECORDS.md) has the rules.

- **T1**: counts under Tier 1 (distinct languages) and Tier 2 (relay steps).
- **T2 only**: counts as a relay step, but merges into another language under Tier 1.

**Totals: #{ RunSteps.size } steps (Tier 2), #{ t1 } distinct languages (Tier 1).**

| # | Language | Tier | Added by | Note |
|---|---|---|---|---|
#{ rows.join("\n") }

This file is generated by `src/LANGUAGES.md.gen.rb`.
END
